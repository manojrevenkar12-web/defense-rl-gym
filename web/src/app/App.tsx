import { Gate } from '../features/gate/Gate';
import { GraderMatrix } from '../features/graders/GraderMatrix';
import { MatrixLegend } from '../features/graders/Legend';
import { PolicyBoard } from '../features/policies/PolicyBoard';
import { RedTeam } from '../features/redteam/RedTeam';
import { day, num, pct, signed } from '../shared/lib/format';
import type { Results } from '../shared/lib/results';
import { useData } from '../shared/lib/useData';
import { Card, ScrollRegion, Section } from '../shared/ui/Section';
import { Code, EmptyState, ErrorState, Skeleton } from '../shared/ui/StateBlock';
import styles from './app.module.css';

function Header({ r }: { r?: Results }) {
  return (
    <header className={styles.hero}>
      <h1>Rewards for defenders, tested against the ways to game them.</h1>
      <p className={styles.heroLede}>
        Two reinforcement-learning environments for defensive security: patch a vulnerable service, and respond to an intrusion in
        a company network. Every reward is checked against patches and policies that should not be paid before anything is trained
        on it.
      </p>
      {r && (
        <p className={styles.meta}>
          Generated by <Code>drg report</Code> on {day(r.generated_at)}, profile <Code>{r.profile}</Code>.
        </p>
      )}
    </header>
  );
}

function Loading() {
  return (
    <div className={styles.loading}>
      <Skeleton height={48} width="45%" label="Loading results" />
      <Skeleton height={320} />
      <Skeleton height={180} />
    </div>
  );
}

function Study({ r }: { r: Results }) {
  const s = r.study;
  const rl = r.rl;
  const h = r.heldout;
  const robust = rl?.policies.robust_clone?.[rl.families[0] ?? ''];
  return (
    <>
      {s ? (
        <Section
          id="graders"
          title="Which patching reward pays only for real fixes?"
          lede={`${r.study_tasks ?? 'Generated'} tasks across six weakness classes. Each comes with patches whose validity is known by construction, and each grader is scored on all of them.`}
          answer={
            <>
              Checking only the report’s two requests pays for <strong>{pct(s.public_tests.invalid_accepted)}</strong> of invalid
              patches. The robust grader pays for <strong>{pct(s.robust.invalid_accepted)}</strong> and refuses{' '}
              {pct(1 - s.robust.valid_accepted)} of valid fixes. It was designed knowing these hacks, so the blind red team below
              is the fairer test.
            </>
          }
        >
          <Card>
            <ScrollRegion label="Grader by patch matrix">
              <GraderMatrix study={s} />
            </ScrollRegion>
            <MatrixLegend />
          </Card>
        </Section>
      ) : (
        <EmptyState title="No grader study in this run">
          Run <Code>drg study</Code> and <Code>drg report</Code> to fill this section.
        </EmptyState>
      )}

      {r.redteam && (
        <Section
          id="redteam"
          title="Patches written by someone who never saw the grader"
          lede="Each set was written from the task folders and a one-page brief only, and graded once. Set 1 became a regression set after its one rejected fix was studied: the task never said administrators may read every record. Set 2 was written after the task text was fixed; its writer wrote genuine fixes only."
        >
          <Card>
            <RedTeam sets={r.redteam} />
          </Card>
        </Section>
      )}

      {rl ? (
        <Section
          id="policies"
          title="What a learned policy does with each reward"
          lede={`PPO on the incident-response environment, ${rl.seeds.length} seeds per variant, judged on unseen seeds by the robust reward: stop the attack, do not cut off people who were not attacked, isolate the attacker’s machines, and be quick. The rule-based analyst’s threshold was tuned on training seeds.`}
          answer={
            robust ? (
              <>
                From scratch, the naive reward teaches the policy to cut everyone off, and the robust reward teaches it to give
                up. Started from a copy of the analyst, the robust reward reaches <strong>{signed(robust.reward)}</strong>,
                stopping {pct(robust.contained)} of attacks while cutting off {num(robust.benign_isolated, 2)} innocent machines
                per episode.
              </>
            ) : undefined
          }
        >
          <Card>
            <PolicyBoard r={r} />
          </Card>
          {h && (
            <p className={styles.footnote}>
              On the blind held-out network the robust policy scores {signed(h.robust_reward)} against{' '}
              {signed(h.baselines.analyst.reward)} for the tuned analyst.
            </p>
          )}
        </Section>
      ) : (
        <EmptyState title="No policies trained in this run">
          Run <Code>drg rl</Code> to train them.
        </EmptyState>
      )}

      {r.bench && (
        <Section id="throughput" title="Throughput on one core">
          <Card>
            <dl className={styles.stats}>
              <div>
                <dt>Incident episodes per second</dt>
                <dd>{num(r.bench.soc_episodes_per_s, 1)}</dd>
              </div>
              <div>
                <dt>Robust patch grades per second</dt>
                <dd>{num(r.bench.patch_grades_per_s, 1)}</dd>
              </div>
            </dl>
          </Card>
        </Section>
      )}

      {r.gate && (
        <Section id="gate" title="Release gate">
          <Card>
            <Gate floors={r.gate.floors} targets={r.gate.targets} />
          </Card>
        </Section>
      )}
    </>
  );
}

export function App({ base = '.' }: { base?: string }) {
  const data = useData(base);
  return (
    <main className={styles.page}>
      <Header r={data.status === 'ready' ? data.results : undefined} />
      {data.status === 'loading' && <Loading />}
      {data.status === 'error' && <ErrorState message={data.message} onRetry={data.retry} />}
      {data.status === 'empty' && (
        <EmptyState title="No results yet">
          Run <Code>drg all --profile full</Code>, then <Code>npm run build</Code> to copy the results here.
        </EmptyState>
      )}
      {data.status === 'ready' && <Study r={data.results} />}
      <footer className={styles.footer}>
        <p>Everything here is simulated: the services, the shell and the company network. No real system is touched.</p>
      </footer>
    </main>
  );
}
